class DisplayImageSegmentation(tf.keras.callbacks.Callback):
    def __init__(self, images, labels, inputShowRate=100, predictionShowRate=5, imageColors=None, labelColors=None, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.images = images
        self.labels = labels
        self.inputShowRate = inputShowRate
        self.predictionShowRate = predictionShowRate
        self.imageColors = imageColors
        self.labelColors = labelColors

    def on_epoch_end(self, epoch, logs=None):
        if self.inputShowRate is not None:
            if epoch % self.inputShowRate == 0:
                show(self.images, colors=self.imageColors)
                show(self.labels, colors=self.labelColors)

        if self.predictionShowRate is not None:
            if epoch % self.predictionShowRate == 0:
                pred = model(self.images)
                pred = pred.numpy()
                show(pred, colors=self.labelColors)

