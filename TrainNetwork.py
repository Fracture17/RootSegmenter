def show(image, size=10, colors=None):
    if isinstance(image, np.ndarray) or isinstance(image, tf.Tensor):
        if image.shape[-1] == 1:
            colors = [1]
        else:
            image = np.squeeze(image)
        if len(image.shape) <= 3:
            image = [image]
    showImages(image, size, colors)


