def makeModel(input, filters, transitions, blockDepth, regularizer=None):
    x = layers.Conv2D(filters, (3,3), padding='same', activation='relu', activity_regularizer=regularizer)(input)
    x = layers.BatchNormalization()(x)

    concatinations = []
    for i in range(transitions):
        x = connectedConvBlock(x, filters, blockDepth, regularizer=regularizer)
        concatinations.append(x)
        x = layers.MaxPool2D()(x)
        x = layers.BatchNormalization()(x)
        filters *= 2

    #This is the most spatially compressed part of the network, so a convolution here sees
    #more of the image than anywhere else.  The 7x7 kernels take advantage of that to pull in
    #global information.  The trained network was produced with these kernels.
    x = layers.Conv2D(filters, (7,7), padding='same', activation='relu', activity_regularizer=regularizer)(x)
    x = layers.BatchNormalization()(x)
    x = layers.Conv2D(filters, (7,7), padding='same', activation='relu', activity_regularizer=regularizer)(x)
    x = layers.BatchNormalization()(x)

    for i in range(transitions):
        filters //= 2
        x = layers.Conv2DTranspose(filters, (4,4), strides=(2,2), padding='same', activation='relu', activity_regularizer=regularizer)(x)
        c = concatinations.pop()
        x = layers.Concatenate()([x, c])
        x = connectedConvBlock(x, filters, blockDepth, regularizer=regularizer)

    x = layers.Conv2D(filters, (3,3), padding='same', activation='relu', activity_regularizer=regularizer)(x)
    beforeOutput = layers.BatchNormalization()(x)

    x = layers.Conv2D(1, (1,1), padding='same', activity_regularizer=regularizer)(beforeOutput)
    output = layers.Activation('sigmoid', dtype='float32')(x)

    return input, output, beforeOutput


def connectedConvBlock(input, filters, depth, dropout=.25, regularizer=None):
    c = input
    convelutions = []
    for _ in range(depth):
        x = layers.Conv2D(filters, (3,3), padding = 'same', activation = 'relu', activity_regularizer=regularizer)(c)
        x = layers.BatchNormalization()(x)
        x = layerDropout(x, dropout)
        convelutions.append(x)
        c = layers.Concatenate()([c, x])

    x = layers.Concatenate()(convelutions)
    return x


#Randomly applies dropout to the entire layer at once, or nothing
def layerDropout(input, prob):
    return layers.Dropout(prob, noise_shape = (None, 1, 1, 1))(input)

