def showImages(images, size=10, colors=None):
    fig, axes = plt.subplots(1, len(images), figsize=(size * len(images), size))
    if len(images) > 1:
        axes = axes.flatten()
    else:
        axes = [axes]
    for img, ax in zip(images, axes):
        if img.dtype == np.float16:
            img = img.astype(np.float32)
        if colors is not None:
            img = label2img(img, colors)
        if img.dtype == int:
            img = img.astype(np.float)
            img /= 255
        ax.imshow(img)
        ax.axis('off')
    plt.tight_layout()
    plt.show()


def label2img(label, colors):
    img = np.zeros((*label.shape[:-1], 3))
    for i, c in enumerate(colors):
        x = np.tile(c, (*label.shape[:-1], 1))
        img += x * label[:,:,i:i+1]
    return img

