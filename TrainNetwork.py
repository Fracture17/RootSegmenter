def pairImages2Labels(imageFile, labelFile, scale=1.0):
    images = []
    labels = []

    for k in labelFile.files:
        img = imageFile[k]
        img = img[..., :-1]
        label = labelFile[k]

        if scale != 1.0:
            s = int(1 // scale)
            img = skimage.measure.block_reduce(img, (s, s, 1), np.max)
            label = skimage.measure.block_reduce(label, (s, s, 1), np.max)

        images.append(img)
        labels.append(label)

    return np.array(images), np.array(labels)

